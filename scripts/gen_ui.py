#!/usr/bin/env python3
"""Generate generated/catdoku_ui.s: the screen backgrounds and the text font.

Sources (assets/src):
  ui_menu.png, ui_levels.png, ui_game.png, ui_plain.png
      160x200 Mode 0 backgrounds, one colour of assets/palette.json per pixel.
      Each becomes a 16 KB screen dump (0xC000 layout), ZX7B compressed, that
      ui_show_background decompresses straight into video memory.
  font.png
      64x24: ASCII 32..95 as 16x4 cells of 4x6 pixels; a lit pixel is part of
      the glyph (3 columns used, the 4th is the gap). Becomes 6 bytes per
      glyph, bits 7..5 = columns 0..2.

    python3 scripts/gen_ui.py           # rewrite generated/catdoku_ui.s
    python3 scripts/gen_ui.py --check   # exit 1 if it would change

zx7b is found like scripts/gen_catdoku_levels.py does.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "assets", "src")
OUTPUT_PATH = os.path.join(ROOT, "generated", "catdoku_ui.s")
BACKGROUNDS = ["menu", "levels", "game", "plain"]   # ui_show_background: A = index


def firmware_rgb(value):
    """CPC firmware colour 0..26 = 9*green + 3*red + blue, levels 0, 128, 255."""
    level = (0, 128, 255)
    return level[value // 3 % 3], level[value // 9], level[value % 3]


def pens():
    values = json.load(open(os.path.join(ROOT, "assets", "palette.json")))["values"]
    table = {}
    for pen, value in enumerate(values):
        table.setdefault(firmware_rgb(value), pen)   # first pen wins
    return table


def mode0_byte(left, right):
    return ((left & 1) << 7 | (left & 2) << 2 | (left & 4) << 3 | (left & 8) >> 2 |
            (right & 1) << 6 | (right & 2) << 1 | (right & 4) << 2 | (right & 8) >> 3)


def screen_dump(path, table):
    image = Image.open(path).convert("RGB")
    if image.size != (160, 200):
        sys.exit(f"{path}: {image.size}, expected 160x200")
    dump = bytearray(16384)
    for y in range(200):
        for x in range(80):
            colours = image.getpixel((2 * x, y)), image.getpixel((2 * x + 1, y))
            missing = [c for c in colours if c not in table]
            if missing:
                sys.exit(f"{path}: ({2 * x}, {y}) colour {missing[0]} is not in assets/palette.json")
            dump[(y & 7) * 2048 + (y >> 3) * 80 + x] = mode0_byte(table[colours[0]], table[colours[1]])
    return bytes(dump)


def font_bytes(path):
    image = Image.open(path).convert("RGB")
    if image.size != (64, 24):
        sys.exit(f"{path}: {image.size}, expected 64x24")
    data = bytearray()
    for code in range(64):
        cx, cy = code % 16 * 4, code // 16 * 6
        for row in range(6):
            bits = 0
            for col in range(3):
                if image.getpixel((cx + col, cy + row)) != (0, 0, 0):
                    bits |= 0x80 >> col
            data.append(bits)
    return bytes(data)


def find_zx7b():
    sys.path.insert(0, HERE)
    from gen_catdoku_levels import find_zx7b as levels_find_zx7b
    return levels_find_zx7b()


def compress(data, zx7b, work, name):
    source, target = os.path.join(work, name + ".bin"), os.path.join(work, name + ".zx7")
    with open(source, "wb") as f:
        f.write(data)
    subprocess.run([zx7b, source, target], check=True, capture_output=True)
    with open(target, "rb") as f:
        return f.read()


def db_lines(data):
    return [f"    .db {', '.join(f'0x{b:02X}' for b in data[i:i + 16])}" for i in range(0, len(data), 16)]


def generate():
    table = pens()
    zx7b = find_zx7b()
    lines = [
        ";; Generated by scripts/gen_ui.py from assets/src/ui_*.png and font.png.",
        ";; Do not edit: change the PNG sources and run the script.",
        ".module catdoku_ui_data",
        "",
        ".area _CODE",
        "",
        ";; ZX7B screen dumps: ui_bg_table holds the address of the LAST byte of each.",
        "ui_bg_table::",
    ]
    lines += [f"    .dw ui_bg_{name}_last" for name in BACKGROUNDS]
    with tempfile.TemporaryDirectory() as work:
        for name in BACKGROUNDS:
            packed = compress(screen_dump(os.path.join(SRC, f"ui_{name}.png"), table), zx7b, work, name)
            lines += ["", f";; ui_{name}.png: {len(packed)} bytes"]
            lines += db_lines(packed[:-1])
            lines += [f"ui_bg_{name}_last:", f"    .db 0x{packed[-1]:02X}"]
    lines += ["", ";; Font: ASCII 32..95, 6 rows per glyph, bits 7..5 = columns 0..2", "ui_font::"]
    lines += db_lines(font_bytes(os.path.join(SRC, "font.png")))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if generated/catdoku_ui.s would change")
    args = parser.parse_args()
    text = generate()
    current = open(OUTPUT_PATH).read() if os.path.exists(OUTPUT_PATH) else None
    if args.check:
        if current != text:
            sys.exit("generated/catdoku_ui.s is stale: run scripts/gen_ui.py")
        return
    with open(OUTPUT_PATH, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
